int rtmr_measure_pe_kernel_image(measurement_config_t *config, rtmrcontext_t *context)
{
	if (!context->kernel_file_path) {
		printf("No kernel image path provided.\n");
		return -1;
	}

	uint8_t digest[SHA384_DIGEST_LENGTH];
	uint8_t *kernel_buf = NULL;
	size_t kernel_size = 0;
	size_t kernel_buf_size = 0;

	if (LoadPeImage(&kernel_buf, &kernel_size, context->kernel_file_path)) {
		printf("Failed to load kernel pe image\n");
		return -1;
	}

	kernel_buf_size = kernel_size;

	// Prepare the kernel image to be measured, i.e., set the appropriate values in the kernel header
	// and write the dtb to the setup_config struct
	if (_setup_kernel_image_for_measurement(config, context, &kernel_buf, &kernel_size, &kernel_buf_size) != 0) {
		printf("Failed to prepare kernel image for measurement\n");
		return -1;
	}

	EFI_STATUS status = MeasurePeImage(EVP_sha384(), digest, kernel_buf, kernel_size);
	if (EFI_ERROR(status)) {
		printf("Failed to measure kernel pe image\n");
		// TODO: why openssl_free?
		OPENSSL_free(kernel_buf);
		return -1;
	}

	evlog_add(context->evlog, config->mr_index, "EV_EFI_BOOT_SERVICES_APPLICATION",
				digest, "Kernel PE Image");
	hash_extend(EVP_sha384(), context->mrs[config->mr_index], digest, SHA384_DIGEST_LENGTH);

	OPENSSL_free(kernel_buf);
	return 0;
}

int rtmr_measure_initrd_image(measurement_config_t *config, rtmrcontext_t *context)
{
	if (!context->initrd_file_path) {
		printf("Failed to open ovmf: no path provided\n");
		return -1;
	}

	uint8_t *initrd_buf = NULL;
	uint64_t initrd_size = 0;
	int ret = read_file(&initrd_buf, &initrd_size, context->initrd_file_path);
	if (ret) {
		printf("Failed to load %s\n", context->initrd_file_path);
		return -1;
	}

	uint8_t digest[SHA384_DIGEST_LENGTH];
	hash_buf(EVP_sha384(), digest, initrd_buf, initrd_size);

	evlog_add(context->evlog, config->mr_index, "EV_EVENT_TAG",
				digest, "Linux initrd");
	hash_extend(EVP_sha384(), context->mrs[config->mr_index], digest, SHA384_DIGEST_LENGTH);

	return 0;
}

